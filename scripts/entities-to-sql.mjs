#!/usr/bin/env node
// Turns Base44 entity JSON schemas into Postgres tables.
//
//   node scripts/entities-to-sql.mjs <app> [entities-dir]   > schema.sql
//
// entities-dir defaults to apps/<app>/entities and holds one <Entity>.json per
// entity, in the format Base44 uses ({ name, type: "object", properties, required }).
// Add "x-access": "shared" | "private" | "public_read" | "admin_write" to pick
// a row-level-security preset (see platform.setup_entity); default is "shared".
import { readdirSync, readFileSync } from 'node:fs';
import { basename, join } from 'node:path';

const BUILTIN = new Set(['id', 'created_date', 'updated_date', 'created_by', 'created_by_id']);

export function columnType(prop = {}) {
  const type = Array.isArray(prop.type) ? prop.type.find((t) => t !== 'null') : prop.type;
  switch (type) {
    case 'string':
      if (prop.format === 'date') return 'date';
      if (prop.format === 'date-time') return 'timestamptz';
      return 'text';
    case 'integer':
      return 'bigint';
    case 'number':
      return 'double precision';
    case 'boolean':
      return 'boolean';
    default:
      // object, array, or untyped: keep the JSON as-is
      return 'jsonb';
  }
}

const ident = (s) => `"${String(s).replaceAll('"', '""')}"`;
const literal = (s) => `'${String(s).replaceAll("'", "''")}'`;

function defaultExpr(prop, type) {
  if (prop.default === undefined) return '';
  if (type === 'jsonb') return ` default ${literal(JSON.stringify(prop.default))}::jsonb`;
  if (type === 'boolean' || type === 'bigint' || type === 'double precision') {
    return ` default ${literal(prop.default)}::${type}`;
  }
  return ` default ${literal(prop.default)}`;
}

export function entityToSql(app, schema, fallbackName) {
  const name = schema.name || fallbackName;
  if (!/^[A-Za-z][A-Za-z0-9_]*$/.test(name)) throw new Error(`invalid entity name: ${name}`);
  const access = schema['x-access'] || 'shared';
  const required = new Set(schema.required || []);
  const table = `${ident(app)}.${ident(name)}`;

  const lines = [`create table if not exists ${table} (`, `  "id" text primary key default replace(gen_random_uuid()::text, '-', '')`];
  const alters = [];
  for (const [field, prop] of Object.entries(schema.properties || {})) {
    if (BUILTIN.has(field)) continue;
    const type = columnType(prop);
    // NOT NULL is left out on purpose: Base44 doesn't enforce "required"
    // server side, so old rows may lack the field and the import would fail.
    const col = `${ident(field)} ${type}${defaultExpr(prop, type)}`;
    lines[lines.length - 1] += ',';
    lines.push(`  ${col}`);
    alters.push(`alter table ${table} add column if not exists ${col};`);
    if (prop.enum && type === 'text') {
      const check = `${name}_${field}_enum`.slice(0, 63);
      alters.push(
        `alter table ${table} drop constraint if exists ${ident(check)};`,
        `alter table ${table} add constraint ${ident(check)} check (${ident(field)} is null or ${ident(field)} in (${prop.enum.map(literal).join(', ')}));`,
      );
    }
    if (required.has(field)) alters.push(`-- ${field} is required in Base44 (enforced by the app, not the database)`);
  }
  lines.push(');');

  return [
    `-- ${name}`,
    ...lines,
    // keeps re-runs working after new fields are added to the JSON schema
    ...alters,
    `select platform.setup_entity(${literal(app)}, ${literal(name)}, ${literal(access)});`,
    '',
  ].join('\n');
}

function main() {
  const [app, dirArg] = process.argv.slice(2);
  if (!app) {
    console.error('usage: entities-to-sql.mjs <app> [entities-dir]');
    process.exit(1);
  }
  const dir = dirArg || join('apps', app, 'entities');
  const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
  const out = ['-- Generated by scripts/entities-to-sql.mjs. Safe to re-run.', `select platform.register_app(${literal(app)});`, ''];
  for (const file of files) {
    const schema = JSON.parse(readFileSync(join(dir, file), 'utf8'));
    out.push(entityToSql(app, schema, basename(file, '.json')));
  }
  process.stdout.write(out.join('\n'));
}

if (import.meta.url === `file://${process.argv[1]}`) main();
